import React, { useState } from 'react';
import Icon from '../Icon.jsx';
import { generateWidget } from '../../api/aiWidgets.js';

const IDEAS = [
  'Bar chart of headcount by department',
  'A metric showing pending leave approvals',
  'List of my pending approvals today',
  'Line chart of attendance trend over 6 months',
  'A sticky note: send payroll inputs by the 25th',
  'Progress bars for onboarding completion',
];

export default function GeminiStudio({ open, onClose, onCreate, summary }) {
  const [prompt, setPrompt] = useState('');
  const [busy, setBusy] = useState(false);
  const [preview, setPreview] = useState(null);
  const [note, setNote] = useState(null);
  const [error, setError] = useState(null);

  if (!open) return null;

  async function generate(text) {
    const p = (text ?? prompt).trim();
    if (!p) return;
    setBusy(true); setError(null); setNote(null); setPreview(null);
    try {
      const { widget, source, note: n } = await generateWidget(p, summary);
      setPreview(widget);
      setNote(source === 'gemini' ? 'Generated by Gemini.' : n || 'Generated locally.');
    } catch (err) {
      setError(err.message || 'Could not generate a widget.');
    } finally {
      setBusy(false);
    }
  }

  function addToDashboard() {
    if (!preview) return;
    onCreate(preview);
    setPreview(null); setPrompt(''); setNote(null);
    onClose();
  }

  return (
    <div className="studio-backdrop" onClick={onClose}>
      <aside className="studio-panel" onClick={(e) => e.stopPropagation()} role="dialog" aria-label="Create a widget with Gemini">
        <header className="studio-head">
          <span className="studio-badge"><Icon name="Sparkles" size={16} /> Gemini widget studio</span>
          <button className="icon-btn ghost" onClick={onClose} aria-label="Close"><Icon name="X" size={18} /></button>
        </header>

        <p className="studio-lead">Describe the widget you want. Gemini builds it and drops it onto your dashboard.</p>

        <div className="studio-field">
          <textarea
            rows={3}
            placeholder="e.g. Bar chart of leave taken by team this month"
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
            onKeyDown={(e) => { if (e.key === 'Enter' && (e.metaKey || e.ctrlKey)) generate(); }}
          />
          <button className="studio-generate" onClick={() => generate()} disabled={busy || !prompt.trim()}>
            {busy ? <><Icon name="RefreshCw" size={16} className="spin" /> Generating…</> : <><Icon name="Wand2" size={16} /> Generate</>}
          </button>
        </div>

        <div className="studio-ideas">
          {IDEAS.map((idea) => (
            <button key={idea} onClick={() => { setPrompt(idea); generate(idea); }}>{idea}</button>
          ))}
        </div>

        {error && <div className="studio-error">{error}</div>}

        {preview && (
          <div className="studio-preview">
            <div className="studio-preview-head"><span>Preview</span>{note && <small>{note}</small>}</div>
            <PreviewCard w={preview} />
            <div className="studio-actions">
              <button className="ghost-btn" onClick={() => generate()}>Regenerate</button>
              <button className="solid-btn" onClick={addToDashboard}><Icon name="Plus" size={15} /> Add to dashboard</button>
            </div>
          </div>
        )}
      </aside>
    </div>
  );
}

// Small static preview so the user sees what they'll get before adding.
function PreviewCard({ w }) {
  const c = w.config || {};
  return (
    <div className={`preview-card tint-${w.tint}`}>
      <div className="preview-card-head"><b>{w.title}</b><span className="preview-type">{w.type}</span></div>
      {w.type === 'metric' && <div className="preview-metric"><strong>{c.value}</strong><span>{c.label}</span></div>}
      {w.type === 'chart' && (
        <div className="preview-bars">
          {(c.series || []).map((s, i) => {
            const max = Math.max(1, ...(c.series || []).map((x) => Number(x.value) || 0));
            return <span key={i} style={{ height: `${(Number(s.value) / max) * 100}%` }} title={`${s.label}: ${s.value}`} />;
          })}
        </div>
      )}
      {w.type === 'list' && <ul className="preview-list">{(c.items || []).slice(0, 3).map((it, i) => <li key={i}>{it.title}<em>{it.sub}</em></li>)}</ul>}
      {w.type === 'progress' && <div className="preview-progress">{(c.rows || []).map((r, i) => <span key={i} style={{ width: `${Math.min(100, (r.value / (r.max || 100)) * 100)}%` }} />)}</div>}
      {w.type === 'note' && <p className="preview-note">{c.text}</p>}
      {w.type === 'quickActions' && <p className="preview-note">{(c.actionIds || []).length} shortcut buttons</p>}
      {w.type === 'link' && <p className="preview-note">Shortcut → {c.to}</p>}
    </div>
  );
}
